CREATE TABLE IF NOT EXISTS staging.sales_transactions (
    transaction_id          text PRIMARY KEY,
    order_id                text NOT NULL,
    customer_id             text NOT NULL,
    customer_name           text,
    customer_age            smallint,
    customer_gender         text,
    customer_segment        text NOT NULL,
    order_date              date NOT NULL,
    order_time              time without time zone NOT NULL,
    sales_channel           text NOT NULL,
    store_id                text NOT NULL,
    store_name              text NOT NULL,
    country                 text NOT NULL,
    region                  text NOT NULL,
    city                    text NOT NULL,
    product_id              text NOT NULL,
    product_name            text NOT NULL,
    product_category        text NOT NULL,
    product_subcategory     text NOT NULL,
    quantity                integer NOT NULL CHECK (quantity >= 0),
    unit_price              numeric NOT NULL CHECK (unit_price >= 0),
    discount_percentage     numeric NOT NULL CHECK (discount_percentage >= 0 AND discount_percentage <= 100),
    sales_amount            numeric NOT NULL,
    cost_amount             numeric NOT NULL,
    profit                  numeric NOT NULL,
    payment_method          text,
    order_status            text NOT NULL,
    shipping_method         text NOT NULL,
    delivery_days           numeric,
    return_flag             char(3) NOT NULL,
    return_reason           text,
    sales_representative    text NOT NULL,
    promotion_code          text,
    customer_rating         numeric,
    inventory_level         numeric,
    order_year              integer NOT NULL
);
